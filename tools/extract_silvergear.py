#!/usr/bin/env python3
"""Reproduce Silvergear resource evidence and C tables from the verified backup."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

SHA256 = '4874af74051372363e8c36ff99e369657648eb353950b41fe2a5a00d35acdb9e'

def printer_render_tables(data):
    if hashlib.sha256(data).hexdigest()!=SHA256:raise ValueError('verified Silvergear backup required')
    app=data[0x2200:]
    return ('/* Generated stock Gray planes020a3cfc and Dot matrix020938c4. */\n'+
        'static const uint8_t printer_gray_thresholds[]={'+','.join(map(str,app[0xa3cfc:0xa3d1c]))+'};\n'+
        'static const int8_t printer_dot_matrix[]={'+','.join(map(str,struct.unpack_from('<16b',app,0x938c4)))+'};\n')

def extract(data):
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError('expected the verified Silvergear 3222882 full-chip backup')
    panel = 0xa7000
    cfg = data[panel+0x38:panel+0x288]
    init, _, size = struct.unpack_from('<III', cfg, 0x4c)
    # 0x50 is the alternate table pointer, not the primary length.
    steps = []
    for pos in range(panel+init, panel+init+size, 8):
        op, value = struct.unpack_from('<II', data, pos)
        if op == 0xffffffff:
            break
        if op not in (0, 1, 3):
            raise ValueError(f'unknown LCD operation {op}')
        steps.append((op, value))
    root = 0xa9998
    offset, length, stride = struct.unpack_from('<III', data, root)
    sensors = []
    for i in range(length//stride):
        pos = root+offset+i*stride
        record = data[pos:pos+stride]
        config, config_bytes, table, table_bytes = struct.unpack_from('<4I', record)
        words = struct.unpack_from('<24I', data, root+config)
        pairs = data[root+table:root+table+table_bytes]
        if record[0x53:0x55] != b'\x01\x01' or pairs[-2:] != b'\xff\xff':
            raise ValueError('unsupported sensor register format')
        sensors.append(dict(record_offset=pos, id=record[0x50], write_address=record[0x51],
            read_address=record[0x52], id_register=struct.unpack_from('<H', record, 0x56)[0],
            config_offset=root+config, config_bytes=config_bytes, config=list(words),
            table_offset=root+table, table_sha256=hashlib.sha256(pairs).hexdigest(),
            pairs=list(zip(pairs[0:-2:2], pairs[1:-2:2]))))
    keys = [struct.unpack_from('<4H', data, 0x2200+0x9ed8c+i*8) for i in range(7)]
    return dict(sha256=SHA256, panel=dict(name=cfg[:32].rstrip(b'\0').decode(),
        native_width=struct.unpack_from('<H', cfg, 0x34)[0],
        native_height=struct.unpack_from('<H', cfg, 0x36)[0],
        config_offset=panel+0x38, init_offset=panel+init, steps=steps,
        camera_scaler_offset=panel+0x108,
        camera_scaler=list(struct.unpack_from('<24I',data,panel+0x108))),
        sensors=sensors, buttons=[dict(code=k[0],center=k[1],tolerance=35) for k in keys],
        temperature_adc=list(struct.unpack_from('<81H', data, 0x2200+0xa347c)))

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('backup',type=Path)
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'boards/silvergear-3222882')
    args=parser.parse_args(); result=extract(args.backup.read_bytes()); args.output.mkdir(parents=True,exist_ok=True)
    (args.output/'resources.json').write_text(json.dumps(result,indent=2)+'\n')
    (args.output/'panel.inc').write_text('/* Generated by tools/extract_silvergear.py; stock SPI 0xa7288. */\n'+
        '\n'.join('    {%du,0x%xu},'%(op,value) for op,value in result['panel']['steps'])+'\n')
    (args.output/'scaler.inc').write_text('/* Stock camera scaler: panel config +0xd0, SPI 0xa7108. */\n'+
        ','.join('0x%08xu'%v for v in result['panel']['camera_scaler'])+'\n')
    text=['/* Generated, ordered stock sensor tables. See resources.json for hashes. */']
    for i,sensor in enumerate(result['sensors']):
        text.append('static const uint8_t silvergear_sensor_%d[][2]={'%i)
        text.extend(' {%s},'%(','.join('0x%02x'%x for x in pair)) for pair in sensor['pairs'])
        text.append('};')
    text.append('static const struct sensor_profile silvergear_sensors[]={')
    for i,sensor in enumerate(result['sensors']):
        c=sensor['config']; flags=(4 if c[10] else 0)|(2 if c[11] else 0)|((c[8]&3)<<8)|((c[0]-1)<<6 if c[0]==3 else c[0]<<10)
        flags|=(c[2]<<26)|(c[3]<<22)|(8 if c[4] else 0)
        text.append(' {0x%x,0x%x,0x%x,0x%x,%du,%du,%du,0x%x,silvergear_sensor_%d,sizeof(silvergear_sensor_%d)/2},'%
            (sensor['id'],sensor['write_address'],sensor['read_address'],sensor['id_register'],c[1],c[6],c[7],flags,i,i))
    text.append('};')
    (args.output/'sensors.inc').write_text('\n'.join(text)+'\n')
    app=args.backup.read_bytes()[0x2200:]
    printer=['/* Generated from verified stock printer tables. */']
    for name,kind,off,n in [('temperature_adc','uint16_t',0xa347c,81),('heat_weights','uint16_t',0xa3cb8,32),('dot_cold','uint8_t',0xa3bf8,96),('dot_hot','uint8_t',0xa3c58,96),('temperature_scale','uint8_t',0xa38cc,84),('temperature_initial','uint32_t',0xa3928,84),('battery_gain','uint8_t',0xa3898,48)]:
        values=struct.unpack_from('<%d%s'%(n,{'uint16_t':'H','uint32_t':'I'}[kind]),app,off) if kind!='uint8_t' else app[off:off+n]
        printer.append('static const %s %s[]={%s};'%(kind,name,','.join(map(str,values))))
    printer.append('static const uint8_t motor_phases[8][4]={'+','.join('{'+','.join(str(v) for v in app[0x8ea8c+4*j:0x8ea90+4*j])+'}' for j in range(8))+'};')
    (args.output/'printer.inc').write_text('\n'.join(printer)+'\n')
    (args.output/'printer-render.inc').write_text(printer_render_tables(args.backup.read_bytes()))
    print(json.dumps(dict(panel={k:v for k,v in result['panel'].items() if k!='steps'},
        sensors=[{k:s[k] for k in ('id','write_address','id_register','table_offset')} for s in result['sensors']],buttons=result['buttons']),indent=2))

if __name__=='__main__':main()
