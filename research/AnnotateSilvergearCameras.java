// Reproduce camera annotations on the verified Silvergear application only.
// @category JT5295.Silvergear
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.Function;
import ghidra.program.model.symbol.SourceType;
import java.security.MessageDigest;

public class AnnotateSilvergearCameras extends GhidraScript {
    private static final String APP_SHA256 =
        "9f9b9e62f9ae552106fbc56d848a17de2ab619f6b1e0fb299ce78fb45f0bc3cd";

    public void run() throws Exception {
        if (!currentProgram.getLanguageID().toString().equals("OpenRISC:LE:32:JT5295"))
            throw new Exception("Expected OpenRISC:LE:32:JT5295");
        byte[] image = new byte[0xa4e00];
        if (currentProgram.getMemory().getBytes(toAddr(0x02000000), image) != image.length)
            throw new Exception("Incomplete application at 02000000");
        StringBuilder hash = new StringBuilder();
        for (byte value : MessageDigest.getInstance("SHA-256").digest(image))
            hash.append(String.format("%02x", value & 255));
        if (!hash.toString().equals(APP_SHA256))
            throw new Exception("Application hash mismatch; no annotations applied");

        long[] addresses = {
            0x02050c60, 0x0203108c, 0x02034fa0, 0x0202bde4,
            0x0204f624, 0x02050ab4, 0x02031638
        };
        String[] names = {
            "Silvergear_camera_select_probe_initialize",
            "Silvergear_camera_MCLK_set",
            "Silvergear_camera_SCCB_initialize",
            "Silvergear_I2C_set_frequency",
            "Silvergear_camera_probe_resource_profiles",
            "Silvergear_camera_apply_mirror_flip",
            "Silvergear_camera_scaled_DMA_configure"
        };
        String[] comments = {
            "Stock camera index 0 selects PE10 low (physical FRONT above display); index 1 selects PE11 low (physical REAR opposite display). PE10/11 are active-high power-down; alternate sensor held high. Starts identification at 16 MHz (02050d38), applies matched clock/table at 02050ee4. Owner-confirmed mapping on 2026-11-02; SDK API uses REAR=0, FRONT=1, reversing the stock index. See research/silvergear/cameras.md.",
            "MCLK source 288 MHz, divider SPR884c[12:8]=(288MHz/request)-1, SPR8850 bit26 gate, SPR8348[11:10]=2; output PD10. Identification 16MHz, fitted ID39 profile 24MHz. Native binutils cross-check and RAM hardware capture verified.",
            "Initializes SCCB on PD13/PD15, mux SPR8348 low3=3. Calls 0202bde4 with 200000 Hz: at CPU144MHz SPR9090=143. Shared pins require printer inactivity.",
            "I2C divisor = CPU_Hz/(5*requested_Hz)-1, SPR9090. Silvergear camera SCCB uses 200kHz, unlike older Action Vision 400kHz.",
            "Resource root SPI a9998, five 88-byte records at a99d8: IDs a0,46,a6,c0,39. Exact ordered register tables/configs generated by tools/extract_silvergear.py. Both fitted cameras read ID39 at page0/reg01 via SCCB42/43. A6 is also host-model tested; other profiles are supported from stock evidence, without hardware acceptance.",
            "Stock index0 FRONT gets flag1; index1 REAR flag0. ID39: FD00,31=flag?02:00. A0:14=flag?13:11. A6:4a=flag?0c:04. ID46:F032,21=flag?66:60,e0=flag?08:04,f0=flag?35:18. IDc0 unchanged. Physical assignments confirmed by owner; hardware-tested on ID39 only.",
            "Scaled NV21: b180 output dimensions, b184/b188 scale ratios, b18c..b1e8 24 coefficients, b060/b064 Y/VU planes. Caller02036314 passes panel-config+0xd0 (argument setup020362f4), SPIa7108. Silvergear coefficients differ from Action Vision. 320x240 pitch320 live DMA verified on both cameras; guards and USB survived ten switches."
        };
        for (int i = 0; i < addresses.length; ++i) {
            Function function = getFunctionAt(toAddr(addresses[i]));
            if (function == null) {
                disassemble(toAddr(addresses[i]));
                function = createFunction(toAddr(addresses[i]), names[i]);
                if (function == null) throw new Exception("Cannot define function " + names[i]);
            }
            function.setName(names[i], SourceType.USER_DEFINED);
            setPlateComment(toAddr(addresses[i]), comments[i]);
            println(String.format("%08x %s", addresses[i], names[i]));
        }
        setEOLComment(toAddr(0x02050d38), "Initial probe MCLK=16MHz, not the final profile clock.");
        setEOLComment(toAddr(0x02050ee4), "Matched profile clock and ordered register table.");
        setEOLComment(toAddr(0x020362f4), "Panel configuration +0xd0 -> stock scaler SPIa7108.");
        createLabel(toAddr(0x020a3478), "Silvergear_stock_camera_index", true, SourceType.USER_DEFINED);
        setPlateComment(toAddr(0x020a3478),
            "Stock index: 0=physical FRONT/PE10, 1=physical REAR/PE11. SDK enum order is reversed. Resource SPI offset = RAM-02000000+2200.");
        println("SILVERGEAR_CAMERA_ANNOTATIONS_PASS app_sha256=" + hash);
    }
}
